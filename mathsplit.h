#ifndef MATHSPLIT_H
#define MATHSPLIT_H

#include <QString>

// task-13: перенос длинных цепочек формул на новые строки.
//
// НА ВХОДЕ — LaTeX-текст ОДНОЙ формулы (без HTML). Функция вызывается
// ТОЛЬКО для формул, которые рендерятся как display (\[ … \]) — в них
// перенос «\\» допустим; для inline формул (в тексте предложения)
// вызывать НЕЛЬЗЯ.
//
// Правило (КАНОНИЧЕСКОЕ — зеркало frontend/js/mathsplit.js; фикстуры:
// tests/testdata/mathsplit_cases.txt, тесты tests/mathsplit_test.cpp и
// tests/mathsplit.test.js). Формулы-цепочки на math100.ru строятся из
// шагов, разделённых группами тонких пробелов «\,\,\,» вокруг отношения
// (обычно «\Leftrightarrow»): один шаг — одна строка, но строка не
// помещается в A4, и формулу приходится «сжимать». Правило раскладывает
// такие цепочки по строкам:
//   1) Формула содержит «\left» или «\right» — НЕ ТРОГАТЬ (перенос внутри
//      \left( … \right) ломает MathJax; такие формулы масштабирует
//      fitWideMath).
//   2) Паттерн REL: RUN + (пробелы) + одно из отношений
//      (\Leftrightarrow \Rightarrow \Leftarrow \iff \to \sim \equiv)
//      + (пробелы) + RUN, где RUN — группа из >= 2 «\,» подряд.
//      Если REL < 2 (меньше трёх шагов) — НЕ ТРОГАТЬ (короткая формула;
//      одиночные «\,» и смысловые пометки вида «15\,\,|\, \cdot T>0»
//      сохраняются как есть).
//   3) Каждое REL заменить: перенос «\\» + отношение + тонкий пробел «\,»
//      (отношение оказывается в начале новой строки: «A / ⇔ B / ⇔ C»).
//
// ОСТАЛЬНЫЕ «\,»-группы (без отношения) НЕ ТРОГАЕМ: на сайте так
// оформляются пометки операций (| …) — перенос там не нужен.

QString splitWideMathChains(const QString &latex);

#endif // MATHSPLIT_H
